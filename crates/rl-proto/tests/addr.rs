//! `is_global`: the public-address test lists, mapping and STUN share.

use std::net::IpAddr;

use rl_proto::is_global;

#[test]
fn only_public_ranges_are_global() {
    let local = [
        "0.1.2.3",
        "10.1.2.3",
        "100.64.0.1",
        "100.127.255.255",
        "127.0.0.1",
        "169.254.1.1",
        "172.16.0.1",
        "172.31.255.255",
        "192.0.0.8",
        "192.0.2.5",
        "192.168.1.1",
        "198.18.0.1",
        "198.19.255.255",
        "198.51.100.9",
        "203.0.113.7",
        "224.0.0.1",
        "239.1.2.3",
        "240.0.0.1",
        "255.255.255.255",
        "::1",
        "::",
        "fc00::1",
        "fdff::1",
        "fe80::1",
        "febf::1",
        "2001:db8::1",
        "ff02::1",
        "::ffff:10.0.0.1",
        "::ffff:127.0.0.1",
        "::ffff:192.168.0.1",
        "::10.0.0.1",
        "::ffff:224.0.0.1",
    ];
    let global = [
        "8.8.4.4",
        "100.63.255.255",
        "100.128.0.1",
        "172.15.255.255",
        "172.32.0.1",
        "198.17.255.255",
        "198.20.0.1",
        "223.255.255.255",
        "2606:4700::1111",
        "2001:db9::1",
        "::ffff:8.8.4.4",
        "fe00::1",
    ];
    for a in local {
        assert!(!is_global(a.parse::<IpAddr>().unwrap()), "{a}");
    }
    for a in global {
        assert!(is_global(a.parse::<IpAddr>().unwrap()), "{a}");
    }
}
