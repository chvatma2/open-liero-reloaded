//! `cargo xtask oracle-gen-weapons`: writes one oracle scenario per weapon of
//! every mod that `content/olx-manifest.ron` imports, to
//! `fixtures/oracle/weapons/<mod slug>/<weapon id>.ron`. The weapon names come
//! from the imported packs (`OLR_CONTENT_DIR`, default `content/packs`). Record
//! the traces afterwards with `cargo xtask oracle-record`.
//!
//! Every scenario is the same apart from the weapon. On FossilFacility's dirt
//! floor (open sky above, dirt below), worm 0 holds the weapon in all five
//! slots and a dummy worm stands 60 px to its right. Worm 0:
//! 1. fires level at the dummy for 1 s (slot 0);
//! 2. aims straight up and fires into the open sky for 0.5 s (slot 1);
//! 3. aims 60° down and fires into the dirt for 0.5 s (slot 2);
//! 4. waits 0.3 s.
//!
//! Each phase fires from a full slot (only the current slot reloads), so
//! weapons with a long reload or rate of fire still fire in every phase.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};
use olr_oracle::{Scenario, WEAPON_SLOTS};
use olr_vfs::DirFs;

use crate::{fetch, root};

/// Where the scenarios go, under `fixtures/oracle`.
pub const DIR: &str = "weapons";
const LEVEL: &str = "FossilFacility.lxl";
const SEED: u32 = 12345;
/// On the dirt floor (surface y ≈ 390 at both x); spawned 6 px above it, so the
/// spawn hole does not reach the floor, and they land by frame 19. The dummy
/// is 60 px away, not 80: at 80 px, close-range weapons and most grenades and
/// mines never reach it (the dummy was hurt in 55 % of the scenarios; at 60 px
/// in 76 %).
const FIRER: (i32, i32) = (118, 384);
const DUMMY: (i32, i32) = (178, 384);
/// The firer's health: enough that its own blasts and falling grenades do not
/// end the later phases.
const FIRER_HP: f32 = 10000.0;
const FRAMES: u32 = 368;
/// The firer's key changes. The LX56 aim (ForceLX56Aim) reaches −90° at frame
/// 159 and 60° at frame 286 with these keys; each phase starts 2 frames later.
/// `change+right` selects the next slot without moving the worm.
const INPUTS: [(u32, &str); 8] = [
    (0, "fire"),
    (100, "up+change+right"),
    (102, "up"),
    (161, "up+fire"),
    (211, "down+change+right"),
    (213, "down"),
    (288, "down+fire"),
    (338, ""),
];

/// The scenario file for `weapon` of OLX mod directory `mod_dir`.
pub fn scenario_text(mod_dir: &str, weapon: &str) -> String {
    let slots = vec![format!("{weapon:?}"); WEAPON_SLOTS].join(", ");
    let inputs: String =
        INPUTS.iter().map(|(f, k)| format!("        (frame: {f}, worm: 0, keys: {k:?}),\n")).collect();
    format!(
        r#"(
    description: "Generated by `cargo xtask oracle-gen-weapons`; do not edit. {mod_dir}'s {weapon} in all 5 slots of worm 0, on FossilFacility's dirt floor, with a dummy worm 60 px to its right. Worm 0 (10000 hp, so its own blasts do not end the run) fires level at the dummy for 1 s (slot 0), aims straight up and fires into the open sky for 0.5 s (slot 1), aims 60 degrees down and fires into the dirt for 0.5 s (slot 2), then waits 0.3 s.",
    level: {LEVEL:?},
    mod: {mod_dir:?},
    seed: {SEED},
    frames: {FRAMES},
    worms: [(x: {}, y: {}), (x: {}, y: {})],
    weapons: [
        (worm: 0, names: [{slots}], current: 0),
        (worm: 1, names: [{slots}], current: 0),
    ],
    health: [(0, {FIRER_HP:?})],
    inputs: [
{inputs}    ],
)
"#,
        FIRER.0, FIRER.1, DUMMY.0, DUMMY.1
    )
}

/// The imported packs: `OLR_CONTENT_DIR`, or `content/packs`.
fn content_dir() -> PathBuf {
    std::env::var_os("OLR_CONTENT_DIR").map_or_else(|| root().join("content/packs"), PathBuf::from)
}

/// Writes every mod's weapon scenarios and removes those of weapons that no
/// longer exist (with their traces).
pub fn run() -> anyhow::Result<bool> {
    let content = content_dir();
    let fixtures = root().join("fixtures/oracle").join(DIR);
    for mod_dir in fetch::mods()? {
        let slug = olr_data::slug::slug(&mod_dir);
        let pack = content.join(format!("olx-{slug}"));
        let m = olr_pack::read_mod(&DirFs::new(&pack))
            .with_context(|| format!("reading {} (run `cargo xtask fetch-olx-content`)", pack.display()))?;
        let out = fixtures.join(&slug);
        std::fs::create_dir_all(&out)?;
        let mut written = BTreeSet::new();
        let mut changed = 0;
        for w in &m.def.weapons {
            let text = scenario_text(&mod_dir, &w.name);
            let sc = Scenario::from_ron(&text).with_context(|| format!("scenario for {}", w.name))?;
            if sc.weapons[0].names[0] != w.name {
                bail!("weapon name {:?} does not survive the scenario file", w.name);
            }
            let path = out.join(format!("{}.ron", w.id));
            if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                std::fs::write(&path, text)?;
                changed += 1;
            }
            written.insert(w.id.clone());
        }
        for stale in stale_files(&out, &written)? {
            println!("removing {}", stale.display());
            std::fs::remove_file(stale)?;
        }
        println!("{mod_dir}: {} weapon scenarios in {}, {changed} written", written.len(), out.display());
    }
    Ok(true)
}

/// Scenarios and traces in `dir` whose weapon id is not in `keep`.
fn stale_files(dir: &Path, keep: &BTreeSet<String>) -> anyhow::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(dir)? {
        let p = e?.path();
        let name = p.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        let id = name.strip_suffix(".ron").or_else(|| name.strip_suffix(".jsonl.gz"));
        if id.is_some_and(|id| !keep.contains(id)) {
            out.push(p);
        }
    }
    out.sort();
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_generated_scenario_parses_and_names_the_weapon() {
        let sc = Scenario::from_ron(&scenario_text("MW 1.0", "Assassin's Shot")).unwrap();
        assert_eq!((sc.mod_dir.as_str(), sc.level.as_str(), sc.frames), ("MW 1.0", LEVEL, FRAMES));
        assert!(sc.weapons.iter().all(|w| w.names == vec!["Assassin's Shot"; WEAPON_SLOTS]));
        assert_eq!(sc.worms[1].x - sc.worms[0].x, 60);
        assert_eq!(sc.health, [(0, FIRER_HP)]);
        let fire: Vec<&str> =
            sc.inputs.iter().map(|c| c.keys.as_str()).filter(|k| k.contains("fire")).collect();
        assert_eq!(fire, ["fire", "up+fire", "down+fire"]);
        assert!(INPUTS.iter().all(|(f, _)| *f < FRAMES));
    }

    /// The committed weapon scenarios are exactly what the generator writes.
    #[test]
    fn committed_weapon_scenarios_are_generated() {
        let dir = root().join("fixtures/oracle").join(DIR);
        let mut n = 0;
        for m in std::fs::read_dir(&dir).unwrap() {
            for e in std::fs::read_dir(m.unwrap().path()).unwrap() {
                let p = e.unwrap().path();
                if p.extension().is_some_and(|x| x == "ron") {
                    let text = std::fs::read_to_string(&p).unwrap();
                    let sc = Scenario::from_ron(&text).unwrap();
                    assert_eq!(text, scenario_text(&sc.mod_dir, &sc.weapons[0].names[0]), "{}", p.display());
                    n += 1;
                }
            }
        }
        assert_eq!(n, 38 + 50);
    }

    #[test]
    fn stale_files_are_those_of_unknown_weapons() {
        let dir = tempfile::tempdir().unwrap();
        for f in ["a.ron", "a.jsonl.gz", "b.ron", "b.jsonl.gz", "notes.txt"] {
            std::fs::write(dir.path().join(f), "").unwrap();
        }
        let keep = BTreeSet::from(["a".to_string()]);
        let names: Vec<String> = stale_files(dir.path(), &keep)
            .unwrap()
            .iter()
            .map(|p| p.file_name().unwrap().to_string_lossy().into_owned())
            .collect();
        assert_eq!(names, ["b.jsonl.gz", "b.ron"]);
    }
}
